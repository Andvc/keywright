def curio(key, title, rarity, trade, effect, description, details, palette, anchor=False):
    asset = {
        "id": f"curio.{key}",
        "category": "curio",
        "title": title,
        "rarity": rarity,
        "trade": trade,
        "description": f"{description} {FINISH[rarity]}",
        "details": details,
        "palette": palette,
        "context": f"What it does in the game: {effect}",
        "replaces": f"assets/ui/curios/{key}.png (the importer scales it 2x into the 56x56 slot)",
        "reference_current": "art/reference/current/curios_2x.png",
    }
    if anchor:
        asset["anchor_for"] = "curio"
        asset["batch"] = 0
    return asset


